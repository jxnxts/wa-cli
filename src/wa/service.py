"""GoWA LaunchAgent (local.wa-mac.gowa): install, start, stop and check.

The agent runs `bin/gowa-run.sh` inside the data folder. The script reads the
password from the Keychain at start time and hands it to GoWA through an
environment variable (never on the command line, never in a file). All GoWA
settings live in the script generated here: 127.0.0.1 only, no read receipts,
no auto-reply, no call rejection, no Chatwoot, no webhook, no web dashboard,
no GoWA MCP, no media download and no periodic "online" presence.

launchd starts agents with a bare PATH (/usr/bin:/bin:/usr/sbin:/sbin), where GoWA
cannot find the ffmpeg it needs for videos and voice notes. The plist sets PATH to the
folder of the ffmpeg found now (if any), Homebrew's folders and the system ones. It is
the only variable in the plist, and it holds no secret.
"""

from __future__ import annotations

import os
import plistlib
import re
import shutil
import subprocess
import time
from pathlib import Path
from typing import Callable, Mapping

from . import companion as comp
from .db import WAError

Runner = Callable[..., subprocess.CompletedProcess]

# GoWA settings. Nothing here is secret; the password comes from the Keychain.
GOWA_ENV: dict[str, str] = {
    "APP_HOST": comp.HOST,
    "APP_OS": "wa-mac",
    "APP_OS_APPEND_VERSION": "false",
    "APP_PAIR_DISPLAY_NAME": "Chrome (Mac OS)",
    "APP_DEBUG": "false",
    "APP_UI_ENABLED": "false",
    "APP_UI_AUTO_UPDATE": "false",
    "MCP_ENABLED": "false",
    "WHATSAPP_AUTO_MARK_READ": "false",
    "WHATSAPP_AUTO_REJECT_CALL": "false",
    "WHATSAPP_AUTO_DOWNLOAD_MEDIA": "false",
    "WHATSAPP_IGNORE_STATUS_MEDIA": "true",
    "WHATSAPP_PRESENCE_ON_CONNECT": "unavailable",
    "WHATSAPP_PRESENCE_PULSE_ENABLED": "false",
    "WHATSAPP_ACCOUNT_VALIDATION": "true",
    "WHATSAPP_LOG_LEVEL": "ERROR",
    "CHATWOOT_ENABLED": "false",
}
# Variables that must stay empty even if they exist in the launchd environment.
GOWA_UNSET = ("WHATSAPP_WEBHOOK", "WHATSAPP_AUTO_REPLY", "WHATSAPP_PROXY", "APP_BASE_PATH",
              "APP_ALLOW_UNAUTHENTICATED", "CHATWOOT_URL", "CHATWOOT_API_TOKEN")


class ServiceError(WAError):
    code = "service_error"


def bin_path(env: Mapping[str, str] | None = None) -> Path:
    return comp.data_dir(env) / "bin" / "gowa"


def run_script_path(env: Mapping[str, str] | None = None) -> Path:
    return comp.data_dir(env) / "bin" / "gowa-run.sh"


def render_run_script(data: Path, port: int) -> str:
    lines = [
        "#!/bin/sh",
        "# Generated by `wa companion service start`. Do not store secrets here.",
        "set -eu",
        "umask 077",
        f'cd "{data}"',
        f'SECRET="$(/usr/bin/security find-generic-password -s {comp.KEYCHAIN_SERVICE} -a {comp.KEYCHAIN_ACCOUNT} -w 2>/dev/null)" || {{',
        '  echo "wa-gowa: credential missing from the Keychain (wa-mac-gowa); run wa companion service start" >&2',
        "  exit 78",
        "}",
        f'export APP_BASIC_AUTH="{comp.AUTH_USER}:$SECRET"',
        "unset SECRET",
        f"export APP_PORT={port}",
    ]
    lines += [f'export {k}="{v}"' for k, v in GOWA_ENV.items()]
    lines += [f"unset {k}" for k in GOWA_UNSET]
    lines.append(f'exec "{data}/bin/gowa" rest')
    return "\n".join(lines) + "\n"


SERVICE_PATH_DIRS = ("/opt/homebrew/bin", "/usr/local/bin", "/usr/bin", "/bin", "/usr/sbin", "/sbin")


def service_path(env: Mapping[str, str] | None = None, which: Callable[..., str | None] = shutil.which) -> str:
    """PATH for the LaunchAgent: the detected ffmpeg's folder first, then Homebrew and the system."""
    env = os.environ if env is None else env
    search = os.pathsep.join([env.get("PATH", ""), *SERVICE_PATH_DIRS])
    dirs: list[str] = []
    ffmpeg = which("ffmpeg", path=search)
    if ffmpeg:
        dirs.append(str(Path(ffmpeg).parent))  # not resolved: a Homebrew Cellar path changes on upgrade
    dirs += SERVICE_PATH_DIRS
    return os.pathsep.join(dict.fromkeys(dirs))


def render_plist(data: Path, path: str | None = None) -> bytes:
    logs = data / "logs"
    return plistlib.dumps(
        {
            "EnvironmentVariables": {"PATH": path or service_path()},
            "Label": comp.LAUNCH_LABEL,
            "ProgramArguments": ["/bin/sh", str(data / "bin" / "gowa-run.sh")],
            "WorkingDirectory": str(data),
            "RunAtLoad": True,
            "KeepAlive": True,
            "ThrottleInterval": 30,
            "ProcessType": "Background",
            "StandardOutPath": str(logs / "gowa.out.log"),
            "StandardErrorPath": str(logs / "gowa.err.log"),
            "Umask": 63,  # 077
        }
    )


def _uid() -> int:
    return os.getuid()


def _domain() -> str:
    return f"gui/{_uid()}"


def _secure_dirs(data: Path) -> None:
    for d in (data.parent, data, data / "bin", data / "logs"):
        d.mkdir(parents=True, exist_ok=True)
    for d in (data, data / "bin", data / "logs"):
        os.chmod(d, 0o700)


def install(env: Mapping[str, str] | None = None, runner: Runner = subprocess.run) -> dict:
    env = os.environ if env is None else env
    data = comp.data_dir(env)
    _secure_dirs(data)
    gowa = bin_path(env)
    if not gowa.exists():
        raise ServiceError(
            f"GoWA binary not found at {gowa}. Build it with scripts/build-gowa.sh.",
            binary=str(gowa),
        )
    created = comp.keychain_create(runner)
    script = run_script_path(env)
    script.write_text(render_run_script(data, comp.port(env)), encoding="utf-8")
    os.chmod(script, 0o700)
    plist = comp.plist_path()
    plist.parent.mkdir(parents=True, exist_ok=True)
    plist.write_bytes(render_plist(data, service_path(env)))
    os.chmod(plist, 0o644)
    return {"data_dir": str(data), "binary": str(gowa), "run_script": str(script), "plist": str(plist),
            "credential_created": created}


def loaded(runner: Runner = subprocess.run) -> dict | None:
    proc = runner(["launchctl", "print", f"{_domain()}/{comp.LAUNCH_LABEL}"], capture_output=True, text=True, timeout=15)
    if proc.returncode != 0:
        return None
    out = proc.stdout or ""
    pid = re.search(r"^\s*pid = (\d+)", out, re.M)
    state = re.search(r"^\s*state = (\S+)", out, re.M)
    return {"pid": int(pid.group(1)) if pid else None, "state": state.group(1) if state else None}


def listen_addresses(port: int, runner: Runner = subprocess.run) -> list[str]:
    proc = runner(["lsof", "-nP", f"-iTCP:{port}", "-sTCP:LISTEN"], capture_output=True, text=True, timeout=15)
    addrs = []
    for line in (proc.stdout or "").splitlines()[1:]:
        m = re.search(r"TCP (\S+) \(LISTEN\)", line)
        if m:
            addrs.append(m.group(1))
    return sorted(set(addrs))


def _wait_health(client: comp.GowaClient, timeout: float, sleep, clock) -> bool:
    deadline = clock() + timeout
    while True:
        if client.health():
            return True
        if clock() >= deadline:
            return False
        sleep(0.5)


UNLOAD_TIMEOUT = 15.0  # seconds to wait for launchd to drop the old job after bootout
BOOTSTRAP_ATTEMPTS = 5
BOOTSTRAP_RETRY_DELAY = 1.0
HEALTH_TIMEOUT = 20.0
RECOVERY_ROUNDS = 2  # extra bootstraps when the job vanished instead of coming up


def _launchctl(runner: Runner, *args: str) -> subprocess.CompletedProcess:
    return runner(["launchctl", *args], capture_output=True, text=True, timeout=30)


def _wait_unloaded(runner: Runner, sleep, clock, timeout: float = UNLOAD_TIMEOUT) -> bool:
    """bootout returns before launchd has finished stopping the job: wait until it is gone."""
    deadline = clock() + timeout
    while loaded(runner):
        if clock() >= deadline:
            return False
        sleep(0.5)
    return True


def _bootstrap(plist: str, runner: Runner, sleep) -> subprocess.CompletedProcess:
    """bootstrap fails (often "5: Input/output error") while the old job is still going away: retry."""
    proc = None
    for attempt in range(BOOTSTRAP_ATTEMPTS):
        if attempt:
            sleep(BOOTSTRAP_RETRY_DELAY)
        proc = _launchctl(runner, "bootstrap", _domain(), plist)
        if proc.returncode == 0 or loaded(runner):
            return subprocess.CompletedProcess(proc.args, 0, proc.stdout, proc.stderr)
    return proc


def start(env: Mapping[str, str] | None = None, runner: Runner = subprocess.run,
          client: comp.GowaClient | None = None, sleep=time.sleep, clock=time.monotonic) -> dict:
    env = os.environ if env is None else env
    try:
        before = comp.plist_path().read_bytes()
    except OSError:
        before = None
    info = install(env, runner)
    changed = before != comp.plist_path().read_bytes()
    is_loaded = loaded(runner)
    attempts = 0
    if is_loaded and changed:
        # kickstart keeps the plist launchd loaded before (its PATH, for one): reload it,
        # waiting for the old job to be gone before loading the new one.
        _launchctl(runner, "bootout", f"{_domain()}/{comp.LAUNCH_LABEL}")
        if not _wait_unloaded(runner, sleep, clock):
            raise ServiceError(f"launchd did not stop the old service within {int(UNLOAD_TIMEOUT)} s; "
                               "run `wa companion service start` again.")
        proc = _bootstrap(info["plist"], runner, sleep)
        action = "reloaded"
    elif is_loaded:
        proc = _launchctl(runner, "kickstart", "-k", f"{_domain()}/{comp.LAUNCH_LABEL}")
        action = "restarted"
    else:
        proc = _bootstrap(info["plist"], runner, sleep)
        action = "loaded"
    attempts += 1
    if proc.returncode != 0:
        raise ServiceError("launchctl failed to start the service.", stderr=(proc.stderr or "").strip()[:300])
    client = client or comp.default_client(env, runner)
    healthy = _wait_health(client, HEALTH_TIMEOUT, sleep, clock)
    # The job can vanish right after a reload (GoWA logs "Received terminated"): load it again.
    for _ in range(RECOVERY_ROUNDS):
        if healthy or loaded(runner):
            break
        proc = _bootstrap(info["plist"], runner, sleep)
        attempts += 1
        if proc.returncode == 0:
            healthy = _wait_health(client, HEALTH_TIMEOUT, sleep, clock)
    st = status(env, runner, client)
    started = bool(healthy and st.get("loaded"))
    out = {**info, **st, "started": started, "action": action, "attempts": attempts}
    if not started:
        out["note"] = (f"The service is not up after {attempts} attempt(s). "
                       f"See {comp.data_dir(env) / 'logs' / 'gowa.err.log'}.")
    return out


def stop(env: Mapping[str, str] | None = None, runner: Runner = subprocess.run) -> dict:
    if not loaded(runner):
        return {"stopped": True, "already": True}
    proc = runner(["launchctl", "bootout", f"{_domain()}/{comp.LAUNCH_LABEL}"], capture_output=True, text=True, timeout=30)
    if proc.returncode != 0:
        raise ServiceError("launchctl bootout falhou.", stderr=(proc.stderr or "").strip()[:300])
    return {"stopped": True, "already": False,
            "note": "The service stopped and will not come back on its own until `wa companion service start`. The session is still saved."}


def status(env: Mapping[str, str] | None = None, runner: Runner = subprocess.run,
           client: comp.GowaClient | None = None) -> dict:
    env = os.environ if env is None else env
    data = comp.data_dir(env)
    port = comp.port(env)
    agent = loaded(runner)
    addrs = listen_addresses(port, runner)
    client = client or comp.default_client(env, runner)
    healthy = client.health()
    auth_required = None
    if healthy:
        anon = comp.GowaClient(client.url, None, opener=client.opener)
        try:
            anon.request("GET", "/devices", device=False, timeout=comp.STATUS_TIMEOUT)
            auth_required = False
        except comp.GowaHTTPError as exc:
            auth_required = exc.status == 401
        except WAError:
            auth_required = None
    mode = None
    if data.exists():
        mode = oct(data.stat().st_mode & 0o777)
    return {
        "label": comp.LAUNCH_LABEL,
        "plist": str(comp.plist_path()),
        "plist_installed": comp.plist_path().exists(),
        "loaded": agent is not None,
        "pid": agent.get("pid") if agent else None,
        "port": port,
        "listen": addrs,
        "loopback_only": bool(addrs) and all(a.startswith("127.0.0.1:") or a.startswith("[::1]:") for a in addrs),
        "healthy": healthy,
        "auth_required": auth_required,
        "data_dir": str(data),
        "data_dir_mode": mode,
        "binary_installed": bin_path(env).exists(),
    }
